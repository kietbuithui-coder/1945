const cache = {};
function glyph(ch) {
  if (cache[ch]) return cache[ch];
  const src = GLYPHS[ch] || GLYPHS[ch.toUpperCase()] || GLYPHS['?'];
  const rows = src.split(',').map((x) => parseInt(x, 16));
  cache[ch] = rows;
  return rows;
}

export function textWidth(str, scale = 1) {
  return str.length * 6 * scale - scale;
}

export function drawText(s, str, x, y, color = '#f2e7d0', scale = 1) {
  let cx = x;
  for (const ch of str) {
    const rows = glyph(ch);
    for (let ry = 0; ry < 7; ry++) {
      for (let rx = 0; rx < 5; rx++) {
        if ((rows[ry] >> (4 - rx)) & 1) {
          for (let yy = 0; yy < scale; yy++) {
            for (let xx = 0; xx < scale; xx++) s.set(cx + rx * scale + xx, y + ry * scale + yy, color);
          }
        }
      }
    }
    cx += 6 * scale;
  }
  return cx;
}

export function drawTextCentered(s, str, cx, y, color = '#f2e7d0', scale = 1) {
  drawText(s, str, Math.round(cx - textWidth(str, scale) / 2), y, color, scale);
}
